import { BufferGeometry, Color, Float32BufferAttribute, MathUtils, Uint32BufferAttribute } from 'three';
import { railLateralNear } from '../world';

// Strands are long tapered tubes in the jelly's own frame (+Y toward the bell).
// Each is a slow swaying curve x(y), z(y); the rail's path is pushed clear so
// the corridor the player flies is always open — but only just.

export type StrandSpec = {
  x0: number;
  z0: number;
  yRoot: number;
  yEnd: number;
  radiusRoot: number;
  radiusTip: number;
  flare: number;
  sway: [amp1: number, wavelength1: number, phase1: number, amp2: number, wavelength2: number, phase2: number];
  color: Color;
  phase: number;
  /** Rail clearance radius (m) enforced by rejection when the strand is generated. */
  clearance: number;
  /** Hero strands are pinned to pass through this local point. */
  pin?: { x: number; y: number; z: number; falloff: number };
  /** Blight along the strand: (y) → 0..1. */
  blight?: (y: number) => number;
};

export const RING_SIDES = 5;
const DEPTH_SPAN = 470;

const railScratch = { x: 0, z: 0, distance: Infinity };

/** Radius of the crown's chamber at local height y: the root cluster parts around the parent's nest. */
export function chamberRadius(y: number) {
  return 34 * MathUtils.smoothstep(y, -140, -72);
}

/**
 * Strands that would pass through the chamber begin below it instead (they
 * fade in), so the nest stays clear without any strand having to bend around it.
 */
export function trimRootToChamber(spec: StrandSpec) {
  const scratch = { x: 0, z: 0 };
  for (let y = spec.yRoot; y >= spec.yEnd; y -= 4) {
    strandCenter(spec, y, scratch);
    if (Math.hypot(scratch.x, scratch.z) < chamberRadius(y) + 3) {
      spec.yRoot = y - 8;
      return;
    }
  }
}

/**
 * True when the strand stays at least `clearance` metres (laterally) from the
 * rail everywhere except within `exemptAround` of its pin. Strands are
 * generated by rejection against this, so none ever crosses the camera's path
 * and none has to bend around it.
 */
export function strandClearOfRail(spec: StrandSpec, clearance: number) {
  const scratch = { x: 0, z: 0 };
  for (let y = spec.yRoot; y >= spec.yEnd; y -= 5) {
    if (spec.pin && Math.abs(y - spec.pin.y) < 14) continue;
    strandCenter(spec, y, scratch);
    if (railLateralNear(y, scratch.x, scratch.z, railScratch).distance < clearance) return false;
  }
  return true;
}

export function strandCenter(spec: StrandSpec, y: number, target = { x: 0, z: 0 }) {
  const depth = MathUtils.clamp(-y / DEPTH_SPAN, 0, 1.4);
  const spread = 1 + spec.flare * depth;
  const [a1, w1, p1, a2, w2, p2] = spec.sway;
  const amplitude = 0.35 + depth * 0.9;
  let x = spec.x0 * spread + amplitude * (a1 * Math.sin((y / w1) * Math.PI * 2 + p1) + a2 * Math.sin((y / w2) * Math.PI * 2 + p2 * 1.7));
  let z = spec.z0 * spread + amplitude * (a1 * Math.cos((y / w1) * Math.PI * 2 + p1 * 1.3) + a2 * Math.sin((y / w2) * Math.PI * 2 + p2));

  if (spec.pin) {
    // Correct the whole curve so it passes through the pin, fading back to
    // natural behaviour with distance along the strand.
    const at = pinOffset(spec);
    const weight = Math.exp(-((y - spec.pin.y) ** 2) / (2 * spec.pin.falloff * spec.pin.falloff));
    x += at.x * weight;
    z += at.z * weight;
  }

  target.x = x;
  target.z = z;
  return target;
}

const pinCache = new WeakMap<StrandSpec, { x: number; z: number }>();
function pinOffset(spec: StrandSpec) {
  let cached = pinCache.get(spec);
  if (cached) return cached;
  const pin = spec.pin!;
  const withoutPin: StrandSpec = { ...spec, pin: undefined, clearance: 0 };
  const natural = strandCenter(withoutPin, pin.y);
  cached = { x: pin.x - natural.x, z: pin.z - natural.z };
  pinCache.set(spec, cached);
  return cached;
}

export function strandRadius(spec: StrandSpec, y: number) {
  const t = MathUtils.clamp((spec.yRoot - y) / Math.max(1, spec.yRoot - spec.yEnd), 0, 1);
  return MathUtils.lerp(spec.radiusRoot, spec.radiusTip, Math.pow(t, 0.7));
}

export type StrandRange = { start: number; count: number; blightBase: Float32Array };

/**
 * Merge many strands into one geometry. Attributes: `position`, `strandColor`,
 * and `aux` = (alongStrand 0..1, phase, blight). Returns per-strand vertex ranges
 * so hero strands can be re-blighted or cleansed later.
 */
export function buildStrandGeometry(specs: StrandSpec[], segmentLength = 9) {
  const positions: number[] = [];
  const colors: number[] = [];
  const aux: number[] = [];
  const indices: number[] = [];
  const ranges: StrandRange[] = [];
  const scratch = { x: 0, z: 0 };
  const tint = new Color();

  for (const spec of specs) {
    const length = spec.yRoot - spec.yEnd;
    const rings = Math.max(6, Math.ceil(length / segmentLength));
    const startVertex = positions.length / 3;
    const blightBase = new Float32Array((rings + 1) * RING_SIDES);
    for (let r = 0; r <= rings; r += 1) {
      const t = r / rings;
      const y = spec.yRoot - length * t;
      strandCenter(spec, y, scratch);
      const radius = strandRadius(spec, y);
      const blight = spec.blight ? spec.blight(y) : 0;
      // A little brightness variation along the strand so it never reads as a flat tube.
      const shade = 0.82 + 0.18 * Math.sin(t * 17 + spec.phase * 6.3);
      tint.copy(spec.color).multiplyScalar(shade);
      for (let s = 0; s < RING_SIDES; s += 1) {
        const angle = (s / RING_SIDES) * Math.PI * 2 + t * 1.5;
        positions.push(scratch.x + Math.cos(angle) * radius, y, scratch.z + Math.sin(angle) * radius);
        colors.push(tint.r, tint.g, tint.b);
        aux.push(length * t, spec.phase, blight);
        blightBase[r * RING_SIDES + s] = blight;
      }
    }
    for (let r = 0; r < rings; r += 1) {
      for (let s = 0; s < RING_SIDES; s += 1) {
        const a = startVertex + r * RING_SIDES + s;
        const b = startVertex + r * RING_SIDES + ((s + 1) % RING_SIDES);
        const c = a + RING_SIDES;
        const d = b + RING_SIDES;
        indices.push(a, c, b, b, c, d);
      }
    }
    ranges.push({ start: startVertex, count: (rings + 1) * RING_SIDES, blightBase });
  }

  const geometry = new BufferGeometry();
  geometry.setAttribute('position', new Float32BufferAttribute(positions, 3));
  geometry.setAttribute('strandColor', new Float32BufferAttribute(colors, 3));
  geometry.setAttribute('aux', new Float32BufferAttribute(aux, 3));
  geometry.setIndex(new Uint32BufferAttribute(indices, 1));
  return { geometry, ranges };
}
